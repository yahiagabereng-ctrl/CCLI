/*===========================================================================
 * Function   : Phonebook_Config_Phonebook_IsValid
 *
 * Description: check if the "phonebook" configuration is valid
 * Input      : - ptr_data: pointer to the values to be checked
 * Output     : - FALSE: configuration is not valid
 *              - TRUE : configuration is     valid
 *===========================================================================*/
bool Phonebook_Config_Phonebook_IsValid(PHONEBOOK__CONFIG__PHONEBOOK *ptr_data)
{
    u8   len_name;
    u8   len_phone_number;

    bool result;
    u16  i;


    for (i = 0; i < PHONEBOOK__PHONEBOOK_SIZE; i++)
    {
        /* verify lengthes */
        len_name         = strlen(ptr_data->phonebook_entry[i].name        );
        len_phone_number = strlen(ptr_data->phonebook_entry[i].phone_number);

        if (
             (len_name         > PHONEBOOK__MAX_LEN_NAME        ) ||
             (len_phone_number > PHONEBOOK__MAX_LEN_PHONE_NUMBER)
           )
        {
            return FALSE;
        }

        if (
             ((len_name >  0) && (len_phone_number == 0)) ||
             ((len_name == 0) && (len_phone_number >  0))
           )
        {
            return FALSE;
        }

        /* verify phone number */
        if (len_phone_number > 0)
        {
            result = Utility_IsPhoneString(ptr_data->phonebook_entry[i].phone_number);
            if (!result)
                return FALSE;
        }
    }


    return TRUE;
}




/*===========================================================================
 * Function   : Phonebook_AddPhonebookEntry
 *
 * Description: add a phonebook entry to the phonebook in the first location empty
 * Input      : - ptr_phonebook_entry: pointer to phonebook entry to be added
 * Output     : - FALSE: phonebook entry not added (phonebook full or phonebook entry not valid)
 *              - TRUE : phonebook entry     added
 *===========================================================================*/
bool Phonebook_AddPhonebookEntry(PHONEBOOK__PHONEBOOK_ENTRY *ptr_phonebook_entry)
{
    bool result;
    u16  i;


    /* verify if the phonebook entry is a valid phonebook entry */
    result = Phonebook_IsValidPhonebookEntry(ptr_phonebook_entry);
    if (!result)
        return FALSE;

    for (i = 0; i < PHONEBOOK__PHONEBOOK_SIZE; i++)
    {
        result = Phonebook_IsPhonebookEntryOccupied(i + 1);
        if (!result)
        {
            /* i-th phonebook entry empty */

            /* add the phonebook entry */
            Phonebook_Config_Phonebook.phonebook_entry[i] = *ptr_phonebook_entry;
            break;
        }
    }

    if (i == PHONEBOOK__PHONEBOOK_SIZE)
        return FALSE;   // phonebook full

    return TRUE;
}




/*===========================================================================
 * Function   : Phonebook_RemovePhonebookEntry
 *
 * Description: remove a phonebook entry from the phonebook (if it is present)
 *                After removing, the entries folowing the removed entry are shifted
 *                in order to eliminate the empty position
 * Input      : - ptr_phonebook_entry: pointer to phonebook entry to be removed (if it is present)
 * Output     : - FALSE: phonebook entry not removed
 *              - TRUE : phonebook entry     removed
 *===========================================================================*/
bool Phonebook_RemovePhonebookEntry(PHONEBOOK__PHONEBOOK_ENTRY *ptr_phonebook_entry)
{
    u16  phonebook_index;
    bool result;
    u8   i;


    /* verify if the phonebook entry is a valid phonebook entry */
    result = Phonebook_IsValidPhonebookEntry(ptr_phonebook_entry);
    if (!result)
        return FALSE;


    /* verify if the phonebook entry is present in phonebook */
    result = Phonebook_IsPhonebookEntry     (ptr_phonebook_entry, &phonebook_index);
    if (result)
    {
        /* phonebook entry     present in phonebook */

        /* remove the phonebook entry from the phopnebook */
        for (i = 0; i < PHONEBOOK__MAX_LEN_NAME;         i++)
            Phonebook_Config_Phonebook.phonebook_entry[phonebook_index - 1].name        [i] = 0x00;
        for (i = 0; i < PHONEBOOK__MAX_LEN_PHONE_NUMBER; i++)
            Phonebook_Config_Phonebook.phonebook_entry[phonebook_index - 1].phone_number[i] = 0x00;

        /* shift the following phonebook entries */
        for (i = (phonebook_index - 1); i < PHONEBOOK__PHONEBOOK_SIZE; i++)
            Phonebook_Config_Phonebook.phonebook_entry[i] = Phonebook_Config_Phonebook.phonebook_entry[i + 1];

        return TRUE;

    }
    else
    {
        /* phonebook entry not present in phonebook */
        return FALSE;
    }
}




