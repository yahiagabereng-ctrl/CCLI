/*
 * The phonebook entries are stored in the first consecutive positions of the phonebook.
 * So if there are 7 phonebook entries stored in the phonebook, these 7 phonebook entries
 * are stored in the position 1, 2, 3, 4, 5, 6, 7 of the phonebook.
 *
 * If a new phonebook entry is added, the new phonebook entries is stored in position 8.
 *
 * If the phonebook entry in position 5 is removed, the phonebook entries in position 6 and 7
 * are shifted in order to eliminate the empty position. So, after the removal,
 * the position occupied are 1, 2, 3, 4, 5, 6.
 */




