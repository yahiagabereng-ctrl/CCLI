/*=============================================================================
 * Function   : Energy_TaskEnergy
 *
 * Description: energy meter task
 * Input      : -
 * Output     : -
 *=============================================================================*/
void Energy_TaskEnergy(void *argument)
{
    ql_event_t event;
    QlOSStatus err;


    Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "TASK ENTRY POINT - ALARM_TMAX - START", __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);


    /* registered the function for signal of new available temperatures */
    DrvTemperature_RegisterSignalNewAdcValues(Energy_NewAdcValues);


    /* creation of timer "TimerAdcValueStart" */
    err = ql_rtos_timer_create(&Energy_TimerHandler_TimerAdcValueStart, QL_TIMER_IN_SERVICE, Energy_AdlCallback_Timer_TimerAdcValueStart, NULL);
    if (err != QL_OSI_SUCCESS)
    {
        Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "QL FUNCTION - ql_rtos_timer_create - ERROR", __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);
    }

    /* creation of timer "TimerAdcValueStop" */
    err = ql_rtos_timer_create(&Energy_TimerHandler_TimerAdcValueStop, QL_TIMER_IN_SERVICE, Energy_AdlCallback_Timer_TimerAdcValueStop, NULL);
    if (err != QL_OSI_SUCCESS)
    {
        Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "QL FUNCTION - ql_rtos_timer_create - ERROR", __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);
    }


    for (;;)
    {
        err = ql_event_try_wait(&event);
        if (err == QL_OSI_SUCCESS)
        {
            /* process the received event */
            Energy_AdlCallback_Message_TaskMsg(&event);
        }
    }
}




/*===========================================================================
 * Function   : Energy_NewAdcValues
 *
 * Description: signal new ADC values available (internal and external)
 * Input      : - adc_value_int: new internal ADC value (mV)
 *              - adc_value_ext: new external ADC value (mV)
 * Output     : -
 *===========================================================================*/
static void Energy_NewAdcValues(u16 adc_value_int, u16 adc_value_ext)
{
    ql_event_t event;
    QlOSStatus err;


    if (Energy_Config_AdcValue.alarm_enabled_status)
    {
        event.id     = TASK_MSG_ID__NEW_ADC_VALUE;
        event.param1 = adc_value_int;
        event.param2 = adc_value_ext;

        err = ql_rtos_event_send(Boot_TaskRef_Energy, &event);
        if (err != QL_OSI_SUCCESS)
        {
            Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "ql_rtos_event_send ERROR", __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);
        }
        else
        {
            Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "ql_rtos_event_send OK"   , __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);
        }
    }
}




/*=============================================================================
 * Function   : Energy_AlarmAdcValue
 *
 * Description: verify if there is an "ADC value alarm" condition
 * Input      : - adc_value: actual ADC value (mV)
 * Output     : -
 *=============================================================================*/
static void Energy_AlarmAdcValue(s16 adc_value)
{
    switch (Energy_Status_AdcValue.status_adc_value)
    {
        // status - temperature regular
        case ADC_VALUE__OK:
            /* status - temperature regular */
            if (adc_value >= Energy_Config_AdcValue.adc_value)   // without hysteresis
            {
                /* "new internal temperature" higher (or equal) than "maximum internal temperature for alarm" */
                if (!Energy_Status_AdcValue.status_change_timer)
                {
                    /* status change timer not active */

                    Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "ADC value: start MAX", __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);

                    Energy_Status_AdcValue.status_change_timer = TRUE;

                    /* request the backup to flash objects */
                    ProgramFlash_RequestWriteBackup(PROGRAM_FLASH__HANDLE_INDEX__018_ENERGY_INFO, PROGRAM_FLASH__FLASH_ID__018_ENERGY_INFO__ADC_VALUE_STATUS);

                    Energy_TimerAdcValueStart_Start(TIME_SEC_TEMP_STATUS_CHANGE * 1000L, FALSE);
                }
            }
            else
            {
                /* "new internal temperature" lower             than "maximum internal temperature for alarm" */
                if ( Energy_Status_AdcValue.status_change_timer)
                {
                    /* status change timer     active */

                    Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "ADC value: stop MAX" , __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);

                    Energy_Status_AdcValue.status_change_timer = FALSE;

                    /* request the backup to flash objects */
                    ProgramFlash_RequestWriteBackup(PROGRAM_FLASH__HANDLE_INDEX__018_ENERGY_INFO, PROGRAM_FLASH__FLASH_ID__018_ENERGY_INFO__ADC_VALUE_STATUS);

                    Energy_TimerAdcValueStart_Stop();
                }
            }
            break;


        // status - ADC value too high (above the maximum)
        case ADC_VALUE__MAX:
            /* status - ADC value too high (above the maximum) */

            if (adc_value <= 0                               )   // with    hysteresis
            {
                if (!Energy_Status_AdcValue.status_change_timer)
                {
                    /* status change timer not active */

                    Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "ADC value: start OK" , __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);

                    Energy_Status_AdcValue.status_change_timer = TRUE;

                    /* request the backup to flash objects */
                    ProgramFlash_RequestWriteBackup(PROGRAM_FLASH__HANDLE_INDEX__018_ENERGY_INFO, PROGRAM_FLASH__FLASH_ID__018_ENERGY_INFO__ADC_VALUE_STATUS);

                    Energy_TimerAdcValueStop_Start(TIME_SEC_TEMP_STATUS_CHANGE * 1000L, FALSE);
                }
            }
            else
            {
                if ( Energy_Status_AdcValue.status_change_timer)
                {
                    /* status change timer     active */

                    Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "ADC value: stop OK"  , __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);

                    Energy_Status_AdcValue.status_change_timer = FALSE;

                    /* request the backup to flash objects */
                    ProgramFlash_RequestWriteBackup(PROGRAM_FLASH__HANDLE_INDEX__018_ENERGY_INFO, PROGRAM_FLASH__FLASH_ID__018_ENERGY_INFO__ADC_VALUE_STATUS);

                    Energy_TimerAdcValueStop_Stop();
                }
            }
            break;


        // status - ADC value status unknown
        default:
            //@@@ TO DO
            break;
    }
}




