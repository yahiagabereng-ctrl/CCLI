/*===========================================================================
 * Function   : Energy_AdlCallback_Message_TaskMsg
 *
 * Description: - task message callback
 * Input      : - ptr_data:
 * Output     : -
 *===========================================================================*/
static void Energy_AdlCallback_Message_TaskMsg(ql_event_t *msg_identifier)
{
    s16   adc_value_int;
    s16   adc_value_ext;

    float power_generated;
    float power_drawn;
    float power_fed;

    s16   power_generated_int;
    s16   power_drawn_int;
    s16   power_fed_int;

    bool  result;


    /* avoid compiler warning unused-but-set-variable */
    (void)result;


    /* debug */
    snprintf(Energy_DebugString, sizeof(Energy_DebugString), "CALLBACK     - MESSAGE     - TASK ENERGY - msg identifier: %d", msg_identifier->id);
    Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, Energy_DebugString, __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);


    switch (msg_identifier->id)
    {
        // event - new internal temperature available
        case TASK_MSG_ID__NEW_ADC_VALUE:
            /* extract the parameters */
            adc_value_int = (s16)msg_identifier->param1;
            adc_value_ext = (s16)msg_identifier->param2;

            snprintf(Energy_DebugString, sizeof(Energy_DebugString), "Current ADC values: %d,%d (mV)", adc_value_int, adc_value_ext);
            Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, Energy_DebugString, __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);


            snprintf(Energy_DebugString,
                     sizeof(Energy_DebugString),
                     "ADC status before new value: %d,%d",
                     Energy_Status_AdcValue.status_adc_value,
                     Energy_Status_AdcValue.status_change_timer);
            Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, Energy_DebugString, __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);


            power_generated = (float)adc_value_int * 2.3f;
            power_drawn     = (float)adc_value_ext * 2.3f;
            power_fed       = power_generated - power_drawn;

            power_generated_int = (s16)lroundf(power_generated);
            power_drawn_int     = (s16)lroundf(power_drawn);
            power_fed_int       = (s16)lroundf(power_fed);

            Energy_Status_AdcValue.power_generated = power_generated_int;
            Energy_Status_AdcValue.power_drawn     = power_drawn_int;
            Energy_Status_AdcValue.power_fed       = power_fed_int;

            /* check the ADC value */
            Energy_AlarmAdcValue(power_fed_int);
            break;



        // event - timeout internal maximum temperature start
        case TASK_MSG_ID__TIMEOUT_ADC_VALUE_START:
            Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "ADC value: MAX", __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);

            /* update the ADC value status */
            Energy_Status_AdcValue.status_adc_value    = ADC_VALUE__MAX;
            Energy_Status_AdcValue.status_change_timer = FALSE;

            /* request the backup to flash objects */
            ProgramFlash_RequestWriteBackup(PROGRAM_FLASH__HANDLE_INDEX__018_ENERGY_INFO, PROGRAM_FLASH__FLASH_ID__018_ENERGY_INFO__ADC_VALUE_STATUS);

            if (Energy_Config_AdcValue.alarm_enabled_status)
            {
                /* enable output 1 */
                Outputs_Event_ManualInt_On();
            }
            break;


        // event - timeout internal maximum temperature stop
        case TASK_MSG_ID__TIMEOUT_ADC_VALUE_STOP:
            Debug_SendDebugString1(DEBUG_TRACE_LEVEL_ENERGY, DEBUG_TRACE_TYPE_LOW, "ADC value: OK" , __FILE__, __LINE__, (ascii *)__FUNCTION__, 0);

            /* update the ADC value status */
            Energy_Status_AdcValue.status_adc_value    = ADC_VALUE__OK;
            Energy_Status_AdcValue.status_change_timer = FALSE;

            /* request the backup to flash objects */
            ProgramFlash_RequestWriteBackup(PROGRAM_FLASH__HANDLE_INDEX__018_ENERGY_INFO, PROGRAM_FLASH__FLASH_ID__018_ENERGY_INFO__ADC_VALUE_STATUS);

            if (Energy_Config_AdcValue.alarm_enabled_status)
            {
                /* disable output 1 */
                Outputs_Event_ManualInt_Off();
            }
            break;



        // unknown event
        default:
            break;
    }
}




