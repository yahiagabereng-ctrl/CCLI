# Refresh rolling SW version + binary identity (repo staging + optional DUT post-check).
# Called from write-deploy-manifest.ps1 and deploy-ccli-session-fix.ps1 — do not skip.

param(
    [string]$ManifestJsonPath = "",
    [string]$DutVersionText = "",
    [string]$DutSha256 = "",
    [string]$DutHost = ""
)

$ErrorActionPreference = "Stop"
$Root = $PSScriptRoot
$ManifestDir = Join-Path $Root "deploy-manifests"
$LatestJson = Join-Path $ManifestDir "CCLI_DEPLOY_LATEST.json"
$LatestMd = Join-Path $ManifestDir "CCLI_DEPLOY_LATEST.md"
$CanonMd = Join-Path $Root "CCLI_SW_VERSION_AND_BINARIES.md"

if (-not $ManifestJsonPath) {
    $candidates = Get-ChildItem -Path $ManifestDir -Filter "CCLI_DEPLOY_*.json" -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -ne "CCLI_DEPLOY_LATEST.json" } |
        Sort-Object LastWriteTime -Descending
    if ($candidates) {
        $ManifestJsonPath = $candidates[0].FullName
    }
}

if (-not (Test-Path $ManifestJsonPath)) {
    Write-Warning "Update-CcliDeployRecord: no manifest JSON at $ManifestJsonPath"
    return
}

$rec = Get-Content -Raw -Path $ManifestJsonPath | ConvertFrom-Json
$RepoRoot = Split-Path $Root -Parent | Split-Path -Parent

if ($DutHost) { $rec | Add-Member -NotePropertyName dut_host -NotePropertyValue $DutHost -Force }
if ($DutVersionText) { $rec | Add-Member -NotePropertyName dut_version_text -NotePropertyValue ($DutVersionText.Trim()) -Force }
if ($DutSha256) {
    $h = ($DutSha256 -replace '\s+.*$', '').Trim().ToLower()
    $rec | Add-Member -NotePropertyName dut_sha256 -NotePropertyValue $h -Force
}

$binPath = [string]$rec.binary
if ($binPath -and (Test-Path $binPath)) {
    $rec | Add-Member -NotePropertyName binary_size_bytes -NotePropertyValue (Get-Item $binPath).Length -Force
}

$full = [string]$rec.version_full
$apkPath = Join-Path $Root "ccli-$full.apk"
if (Test-Path $apkPath) {
    $rec | Add-Member -NotePropertyName apk_path -NotePropertyValue $apkPath -Force
    $rec | Add-Member -NotePropertyName apk_sha256 -NotePropertyValue ((Get-FileHash -Algorithm SHA256 -Path $apkPath).Hash.ToLower()) -Force
    $rec | Add-Member -NotePropertyName apk_size_bytes -NotePropertyValue (Get-Item $apkPath).Length -Force
}

$verSidecar = Join-Path $Root "ccli-VERSION"
if (Test-Path $verSidecar) {
    $rec | Add-Member -NotePropertyName staging_version_file -NotePropertyValue $verSidecar -Force
}

$rec | Add-Member -NotePropertyName record_updated_utc -NotePropertyValue (Get-Date).ToUniversalTime().ToString("o") -Force
$rec | ConvertTo-Json -Depth 6 | Set-Content -Path $LatestJson -Encoding UTF8

$manifestMd = ($ManifestJsonPath -replace '\.json$', '.md')
$shaMatch = ""
if ($rec.sha256 -and $rec.dut_sha256) {
    $shaMatch = if ($rec.sha256 -eq $rec.dut_sha256) { "**MATCH**" } else { "**MISMATCH - investigate**" }
}

$apkLatest = "(no matching apk on disk)"
if ($rec.apk_path) {
    $apkLatest = '`{0}` SHA256 `{1}`' -f (Split-Path $rec.apk_path -Leaf), $rec.apk_sha256
}
$dutShaLatest = "(post-deploy not captured yet)"
if ($rec.dut_sha256) {
    $dutShaLatest = "``$($rec.dut_sha256)`` $shaMatch"
}
$dutVerLatest = "(post-deploy not captured yet)"
$dutVerBlock = "(run deploy-ccli-session-fix.ps1 to capture DUT identity)"
if ($rec.dut_version_text) {
    $dutVerLatest = "see below"
    $dutVerBlock = $rec.dut_version_text
}
$manifestLeafLatest = Split-Path $manifestMd -Leaf
$labYamlLeaf = Split-Path $rec.lab_yaml -Leaf

$latestBody = @"
# CCLI deploy - LATEST (auto-generated)

Do not edit by hand. Regenerated by ``Update-CcliDeployRecord.ps1`` on every manifest write / deploy.

| Field | Value |
|-------|-------|
| **Version** | **$($rec.version_full)** ($($rec.codename)) |
| **Git** | ``$($rec.git_commit)`` |
| **Manifest** | ``$manifestLeafLatest`` |
| **Staging binary** | ``lab/tg544-openwrt/ccli-bin`` |
| **SHA256 (staging)** | ``$($rec.sha256)`` |
| **Size (staging)** | $($rec.binary_size_bytes) bytes |
| **APK** | $apkLatest |
| **Lab yaml** | ``$labYamlLeaf`` |
| **DUT host** | $($rec.host) |
| **DUT ``/usr/sbin/ccli`` SHA256** | $dutShaLatest |
| **DUT version (text)** | $dutVerLatest |
| **Recorded (UTC)** | $($rec.record_updated_utc) |

``````
$dutVerBlock
``````

Full manifest: [$manifestLeafLatest]($manifestLeafLatest)

Canonical policy: [CCLI_SW_VERSION_AND_BINARIES.md](../CCLI_SW_VERSION_AND_BINARIES.md)
"@

Set-Content -Path $LatestMd -Value $latestBody -Encoding UTF8

if (-not (Test-Path $CanonMd)) {
    Write-Warning "Missing $CanonMd - run doc seed once"
    return
}

$canon = Get-Content -Raw -Path $CanonMd
$start = "<!-- CURRENT_START -->"
$end = "<!-- CURRENT_END -->"
$i0 = $canon.IndexOf($start)
$i1 = $canon.IndexOf($end)
if ($i0 -lt 0 -or $i1 -lt 0) {
    Write-Warning "CCLI_SW_VERSION_AND_BINARIES.md missing CURRENT markers"
    return
}

$apkCell = "-"
if ($rec.apk_path) {
    $apkCell = '`{0}` SHA256 `{1}`' -f (Split-Path $rec.apk_path -Leaf), $rec.apk_sha256
}
$dutCell = "*(deploy to capture)*"
if ($rec.dut_sha256) {
    $dutCell = "SHA256 ``$($rec.dut_sha256)`` $shaMatch"
}
$changeLine = "-"
if ($rec.changes) {
    $changeLine = $rec.changes -join "; "
}
$yamlLeaf = Split-Path $rec.lab_yaml -Leaf
$manifestLeaf = Split-Path $manifestMd -Leaf

$block = @"
$start
## Current lab DUT pin (auto-updated)

| Item | Value |
|------|-------|
| **Software** | **$($rec.version_full)** ($($rec.codename)) |
| **Git (build tree)** | ``$($rec.git_commit)`` |
| **DUT SSH** | ``root@$($rec.host)`` (LAN1 ``192.168.10.1`` or LAN2 ``192.168.1.130``) |
| **Staging ``ccli-bin``** | SHA256 ``$($rec.sha256)`` ($($rec.binary_size_bytes) B) |
| **OpenWrt APK** | $apkCell |
| **DUT ``/usr/sbin/ccli``** | $dutCell |
| **Config on DUT** | ``/etc/ccli/lab.yaml`` = ``$yamlLeaf`` |
| **Last manifest** | [$manifestLeaf](deploy-manifests/$manifestLeaf) |
| **Updated (UTC)** | $($rec.record_updated_utc) |

**Changes in last deploy:** $changeLine
$end
"@

$newCanon = $canon.Substring(0, $i0) + $block + $canon.Substring($i1 + $end.Length)
Set-Content -Path $CanonMd -Value $newCanon -Encoding UTF8

Write-Host "Updated: $LatestJson" -ForegroundColor Green
Write-Host "Updated: $LatestMd" -ForegroundColor Green
Write-Host "Updated: $CanonMd (CURRENT block)" -ForegroundColor Green
